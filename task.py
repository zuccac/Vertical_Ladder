def task_sector(base, phi):
    m = fit_static(base)
    m.regimes = {'pre': REGIME['pre'], 'post': REGIME['pre']}
    m.phi = phi
    m.name = f'{base}_task{phi:.6f}'
    base_core = m._solve_core

    def core(P, Ahat, regime, normed, _m=m, _f=base_core):
        if regime == 'post' and normed:
            pi0 = _m.pi
            _m.pi = dict(A=(1 - _m.phi) * pi0['A'], E=pi0['E'], R=pi0['R'] + _m.phi * pi0['A'])
            try:
                return _f(P, Ahat, regime, normed)
            finally:
                _m.pi = pi0
        return _f(P, Ahat, regime, normed)
    m._solve_core = core
    return m


def spl_of(m, base, fast=False):
    if fast:
        PG = np.linspace(20, 150, 9)
        AG = np.concatenate([np.linspace(0.5, 20, 5), np.linspace(24, 300, 9)])
        return surrogates(m, PG, AG, 'taskmatchfast'), PG, AG
    PG, AG = grid_of(base)
    return surrogates(m, PG, AG, 'task'), PG, AG


def run(base, phi):
    m = task_sector(base, phi)
    spl, PG, AG = spl_of(m, base)
    r = gov(m, spl, PG, AG)
    mp_pre = m.mrp_P(P0, m.Ahat_star, 'pre', h=2.0)
    mp_post = m.mrp_P(P0, m.Ahat_star, 'post', h=2.0)
    rise = mp_post - mp_pre
    rf = gov(m, spl, PG, AG, wP_post=m.w_P + rise)
    c, d = crossover_any(f'{m.name}', m, spl, 0.0, rise)
    mrp_post = m.mrp_A(P0, m.Ahat_star, 'post', h=2.0)
    E = r['paths']['my_AI']['E']
    return dict(phi=phi, r={k: v for k, v in r.items() if k != 'paths'}, rf={k: v for k, v in rf.items() if k != 'paths'},
                cross=c, gain=d, mrpshare=100 * mrp_post / m.w_A, mprise=100 * (mp_post / mp_pre - 1),
                hzero=100 * E[SHOCK] / r['paths']['my_AI']['e_ss'])


def match_phi(base='Law_09', target=72.0):
    prev = engine_final.FAST
    engine_final.FAST = True

    def f(phi):
        m = task_sector(base, phi)
        spl, PG, AG = spl_of(m, base, fast=True)
        e = Economy(m, spl[0], spl[1], H=60, shock=True)
        E = e.entry(e.solve_rolling(3))
        return 100 * hwin(E, e.e_ss) - target
    try:
        return brentq(f, 0.3, 0.95, xtol=0.0005)
    finally:
        engine_final.FAST = prev


def sg(v):
    out = f'{v:+.0f}'
    return '0' if out in ('+0', '-0') else out


