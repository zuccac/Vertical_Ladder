"""numcheck_numbers.py -- reads logs/numcheck_*.log (numcheck.py) and writes out/numbers_numcheck_v1.tex:
largest difference across planning windows (130, 160, 200 years) and across four starting paths, both sectors."""
import re
H, K, S = [], [], []
for key in ('Law_09', 'IB'):
    L = open(f'logs/numcheck_{key}.log').read()
    hw = [tuple(map(float, m)) for m in re.findall(r'H=\d+: long-horizon hiring ([\d.]+)% of no-AI, seniors44 ([\d.]+)%; success True, at bound 0', L)]
    st = [tuple(map(float, m)) for m in re.findall(r'start=\w+: long-horizon hiring ([\d.]+)%, seniors44 ([\d.]+)%; success True', L)]
    assert len(hw) == 3 and len(st) == 4, key
    H.append(max(abs(a[0] - hw[0][0]) for a in hw)); K.append(max(abs(a[1] - hw[0][1]) for a in hw))
    S.append(max(max(abs(a[0] - st[0][0]), abs(a[1] - st[0][1])) for a in st))
up = lambda v, d: f'{(int(v * 10**d) + 1) / 10**d:.{d}f}'
open('out/numbers_numcheck_v1.tex', 'w').write('% generated by numcheck_numbers.py -- do not edit by hand\n'
    + r'\newcommand{\ncHhire}{%s}' % up(max(H), 3) + '\n' + r'\newcommand{\ncHsen}{%s}' % up(max(K), 3) + '\n'
    + r'\newcommand{\ncStart}{%s}' % up(max(S), 3) + '\n')
print(max(H), max(K), max(S))
