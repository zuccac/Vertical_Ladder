"""cournot_numbers.py -- macros for the market-structure robustness check (cournot.py results)."""
import os
from core import th, load
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
from cournot import make
MAC = []
W = {4: 'Four', 20: 'Twenty'}
for N in (4, 20):
    s2L = load(f'cournot_sig_{N}')
    MAC.append((f'cn{W[N]}sigtwo', f'{s2L:.2f}'))
    for key, sec in (('Law_09', 'Law'), ('IB', 'IB')):
        r = load(f'cournot_govw_{key}_{N}')
        m = make(key, N, s2L if key == 'Law_09' else 1)
        MAC += [(f'cn{sec}{W[N]}alphaP', f'{m.alpha_P:.2f}'),
                (f'cn{sec}{W[N]}hmy', f'{100 * r["my"]["hrat"]:.0f}'), (f'cn{sec}{W[N]}hpat', f'{100 * r["pat"]["hrat"]:.0f}'),
                (f'cn{sec}{W[N]}gap', f'{r["gap"]:.0f}'), (f'cn{sec}{W[N]}Kmy', f'{100 * r["my"]["K44rat"]:.0f}'),
                (f'cn{sec}{W[N]}Kpat', f'{100 * r["pat"]["K44rat"]:.0f}'), (f'cn{sec}{W[N]}capgap', f'{r["capgap"]:.0f}'),
                (f'cn{sec}{W[N]}KpatnoAI', f'{100 * r["pat"]["K44noAI"]:.0f}')]
from engine_final import CALIB
for key, sec in (('Law_09', 'Law'), ('IB', 'IB')):       # one firm: the paper's baseline, in the same format
    r = load(f'gov_E_{key}')
    MAC += [(f'cn{sec}OnealphaP', f'{CALIB[key]["alpha_P"]:.2f}'), (f'cn{sec}OneKpatnoAI', f'{100 * r["pat"]["K44noAI"]:.0f}')]
with open(OUT + 'numbers_cournot_v3.tex', 'w') as fh:
    fh.write('% generated by cournot_numbers.py -- do not edit by hand\n')
    for n, v in MAC:
        fh.write(f'\\newcommand{{\\{n}}}{{{th(v)}}}\n')
print(open(OUT + 'numbers_cournot_v3.tex').read())
