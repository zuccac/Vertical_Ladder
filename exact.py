from core import EXPOSURE, H_LONG, grid_of, surrogates, sector, load

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
SIG = load('sig_v29')
S2 = {'Law_09': SIG['Law_09'], 'IB': 1 + EXPOSURE * (SIG['Law_09'] - 1)}
TMAX = 45
# the paper's text; written only if the checks pass
EXTEXT = "We check the solutions against exact profit maximisation in two ways. First, with no weight on the future and juniors treated alike, short-horizon hiring in each year solves the first-order condition of Corollary~\\ref{cor:static}, or is zero if the juniors carried over already exceed the level it implies. Re-solving the projected-scenario paths year by year in this way with the exact $\\Pi^*$ reproduces hiring to within 0.15\\% of the usual intake in every year in both sectors, gives the same years of zero hiring, and changes the year-44 senior stock by less than 0.01. Second, along both firms' paths in years 5 to 44 the approximation's relative error in $\\Pi^*$ is below 0.005\\% and its error in $\\partial\\Pi^*/\\partial\\hat A$ below \\$1.1k a year, against a junior wage of \\$372k in law and \\$345k in banking. Only the short-horizon paths can be re-solved exactly in this way; errors away from the solution paths are reported under Numerics in Appendix~\\ref{sec:limits}."


def exact_short(key):
    m = sector(key, S2[key])
    PG, AG = grid_of(key)
    spl = surrogates(m, PG, AG, 'v29')
    e = Economy(m, spl[0], spl[1], H=H_LONG, shock=True)
    g = load(f'gov_E_{key}')['paths']['my_AI']
    x_s = np.array(g['x'])
    x = np.full(e.nx, e.e_ss)
    for t in range(SHOCK, TMAX):
        j = t - SHOCK
        x[j] = 0.0
        P, A = e.paths(x)
        carried = A[t]
        f = lambda Ah: m.mrp_A(P[t], Ah, 'post', h=1.0) - m.w_A
        lo, hi = 0.3, 3.0 * m.Ahat_star
        if f(lo) <= 0:
            target = lo                      # even the first junior adds less than the wage: hire none
        elif f(hi) >= 0:
            raise RuntimeError(f'{key} year {t}: target junior stock above the search range')
        else:
            target = brentq(f, lo, hi, xtol=1e-8)
        x[j] = max(0.0, target - carried)
    E_ex, E_s = e.entry(x)[:TMAX], e.entry(x_s)[:TMAX]
    P_ex, _ = e.paths(x)
    P_s, _ = e.paths(x_s)
    dev = 100 * np.max(np.abs(E_ex[SHOCK:] - E_s[SHOCK:])) / e.e_ss
    zeros_same = [t for t in range(SHOCK, TMAX) if E_ex[t] <= 0.5] == [t for t in range(SHOCK, TMAX) if E_s[t] <= 0.5]
    return dict(dev_pct=dev, zeros_same=zeros_same, dP44=abs(P_ex[44] - P_s[44]))


def surrogate_errors(key):
    m = sector(key, S2[key])
    PG, AG = grid_of(key)
    spl = surrogates(m, PG, AG, 'v29')
    e = Economy(m, spl[0], spl[1], H=H_LONG, shock=True)
    lev, der = [], []
    for nm in ('my_AI', 'pat_AI'):
        x = np.array(load(f'gov_E_{key}')['paths'][nm]['x'])
        P, A = e.paths(x)
        for t in range(SHOCK, TMAX):
            ex = m.operating_surplus(P[t], A[t], 'post')
            lev.append(abs(float(spl[1].ev(P[t], A[t])) - ex) / abs(ex))
            der.append(abs(float(spl[1].ev(P[t], A[t], dy=1)) - m.mrp_A(P[t], A[t], 'post', h=1.0)))
    return dict(lev_pct=100 * max(lev), der=max(der))


