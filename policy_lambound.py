"""policy_lambound.py (12 Nov 2026): the career-implied weights and Table 'lambound' only; the differences in hiring
they imply are written by lambda_numbers.py. Original docstring:
policy_lambound_v1.py -- rebuild (8 Nov 2026) of the lost policy_v1.py and lambound_v4.py /
make_lambound_numbers_v4.py.

policy: share of juniors reaching year n that must be promoted, p = delta_P (1 - s) / (l delta_A s),
s = (1 - delta_A)^n, for promotion lags of 6 to 10 years at each sector's leverage and exit rates
(numbers_policy). lambound: the weight on the future implied by partner careers (Appendix B, Table 'lambound')
and the differences in hiring it implies, by linear interpolation on the unrounded Table 4 results
(numbers_lambound, lambound_table).
"""
import os
import numpy as np
from core import th, load, cached
from engine_final import CALIB

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
os.makedirs(OUT, exist_ok=True)
WORDN = {6: 'six', 7: 'seven', 8: 'eight', 9: 'nine', 10: 'ten'}
SEC = {'Law': CALIB['Law_09'], 'IB': CALIB['IB']}


def p_needed(dA, dP, lev, n):
    s = (1 - dA) ** n
    return dP * (1 - s) / (lev * dA * s)


def lam_const(dA, dP, n, beta):
    return ((1 - dP) ** n * (1 - beta * (1 - dP)) / (1 - beta * (1 - dP) ** 2)
            * (1 - beta * (1 - dP) * (1 - dA)) / (1 - beta * (1 - dA)))


def lam_inc_fixed(r, n, L, beta, dP):
    if r <= n:
        return 0.0
    k = min(r - n, L)
    return (1 - beta * (1 - dP)) * (1 - beta ** k) / (1 - beta)


def lam_fixed(r, n, L, beta, dP, dA):
    li, li1 = lam_inc_fixed(r, n, L, beta, dP), lam_inc_fixed(r - 1, n, L, beta, dP)
    return min(1.0, (li - beta * (1 - dA) * li1) / (1 - beta * (1 - dA)))


def lam_all(dA, dP, n, beta):
    L = 1 / dP
    med = lam_fixed(L / 2, n, L, beta, dP, dA)
    rs = np.linspace(0, L, 20001)[1:]
    mean = float(np.mean([lam_fixed(r, n, L, beta, dP, dA) for r in rs]))
    return dict(const=min(1.0, lam_const(dA, dP, n, beta)), med=med, mean=mean)


if __name__ == '__main__':
    MAC = []
    for sec, c in SEC.items():
        for n in range(6, 11):
            p = p_needed(c['delta_A'], c['delta_P'], c['leverage'], n)
            MAC.append((f'pol{sec}p{WORDN[n]}', f'{100 * p:.0f}'))
            MAC.append((f'pol{sec}fall{WORDN[n]}', f'{100 - 100 * p:.0f}'))
    with open(OUT + 'numbers_policy_v5.tex', 'w') as fh:
        fh.write('% generated by policy_lambound.py -- do not edit by hand\n')
        for n_, v in MAC:
            fh.write(f'\\newcommand{{\\{n_}}}{{{th(v)}}}\n')

    BETAS = [1 / 1.05] + [1 / (1 + r) for r in np.linspace(0.03, 0.08, 51)]
    ROWS = (('Law', 0.03, 'Law, 3\\%'), ('Law', 0.038, 'Law, 3.8\\%'), ('Law', 0.05, 'Law, 5\\%'),
            ('IB', 0.04, 'Banking, 4\\%'), ('IB', 0.065, 'Banking, 6.5\\%'), ('IB', 0.08, 'Banking, 8\\%'))
    lines, allv, base = [], {'Law': [], 'IB': []}, {}
    for sec, dP, lab in ROWS:
        c = SEC[sec]
        vals = [lam_all(c['delta_A'], dP, c['n_bar'], b) for b in BETAS]
        cells = []
        for k in ('const', 'med', 'mean'):
            v0 = vals[0][k]
            vs = [v[k] for v in vals[1:]]
            cells.append(f'{v0:.2f} ({min(vs):.2f}--{max(vs):.2f})')
            allv[sec] += vs + [v0]
        if abs(dP - c['delta_P']) < 1e-9:
            base[sec] = vals[0]
        lines.append(f'{lab} & ' + ' & '.join(cells) + ' \\\\')
    open(OUT + 'lambound_table_v9.tex', 'w').write('\n'.join(lines) + '\n')
    MAC = []
    for sec in ('Law', 'IB'):
        lo, hi = min(allv[sec]), max(allv[sec])
        b = base[sec]
        MAC += [(f'lbb{sec}lo', f'{lo:.2f}'), (f'lbb{sec}hi', f'{hi:.2f}'), (f'lbb{sec}const', f'{b["const"]:.2f}'),
                (f'lbb{sec}med', f'{b["med"]:.2f}'), (f'lbb{sec}mean', f'{b["mean"]:.2f}')]
        print(sec, MAC[-5:], flush=True)
    with open(OUT + 'numbers_lambound_weights_v2.tex', 'w') as fh:
        fh.write('% generated by policy_lambound.py -- do not edit by hand\n')
        for n_, v in MAC:
            fh.write(f'\\newcommand{{\\{n_}}}{{{th(v)}}}\n')
