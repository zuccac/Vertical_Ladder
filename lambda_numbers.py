"""lambda_numbers.py (12 Nov 2026) -- numbers for the weight on the future from the full-model decision-maker
(lambda_full.py): Table 4 (numbers_joint_v5), the credit table rows of numbers_checks (numbers_checks_v5, other
rows unchanged from checks_v4) and the career-implied differences (numbers_lambound_v7, weights from
policy_lambound_v2). A weight of one is the long-horizon firm, so every pass-through now has a lambda = 1 point."""
import os
import re
import numpy as np
from core import th, load

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
LAMS = ((0.0, 'Zero'), (0.25, 'Quarter'), (0.5, 'Half'), (0.75, 'Threeq'), (1.0, 'One'))
SS = ((0.0, 'Fixed'), (0.5, 'Half'), (1.0, 'Full'))
SECS = (('Law_09', 'Law'), ('IB', 'IB'))


def res(key, lam, s):
    return load(f'lamfull_{key}_{lam}_{s}')


def write(name, MAC, src):
    with open(OUT + name, 'w') as fh:
        fh.write(f'% generated by {src} -- do not edit by hand\n')
        for n, v in MAC:
            fh.write(f'\\newcommand{{\\{n}}}{{{th(v)}}}\n')


# Table 4
MAC = []
for key, sec in SECS:
    for s, sw in SS:
        hl = res(key, 1.0, s)['h']
        MAC.append((f'jt{sec}long{sw}', f'{hl:.0f}'))
        for lam, lw in LAMS[:-1]:
            h = res(key, lam, s)['h']
            MAC += [(f'jt{sec}{lw}{sw}', f'{hl - h:.0f}'), (f'jt{sec}{lw}{sw}h', f'{h:.0f}')]
write('numbers_joint_v7.tex', MAC, 'lambda_numbers.py')

# credit table rows (lambda 0..1, pay fixed); the other check rows are carried over from checks_v4
old = open(OUT + 'numbers_checks_v8.tex').read()
keep = [(n, v) for n, v in re.findall(r'\\newcommand\{\\([A-Za-z]+)\}\{([^}]*)\}', old.replace('{,}', ','))
        if not re.match(r'ck(Law|IB)lam', n)]
MAC = []
for key, sec in SECS:
    for lam, lw in LAMS:
        r = res(key, lam, 0.0)
        MAC += [(f'ck{sec}lam{lw}h', f'{r["h"]:.0f}'), (f'ck{sec}lam{lw}K', f'{r["K44"]:.0f}'), (f'ck{sec}lam{lw}cut', f'{100 - r["h"]:.0f}')]
write('numbers_checks_v9.tex', keep + MAC, 'lambda_numbers.py (credit rows) and checks.py (other rows)')


# career-implied differences: weights from policy_lambound_v2, differences interpolated on lambda_full results
def gap(key, lam, s):
    pts = [l for l, _ in LAMS]
    hl = res(key, 1.0, s)['h']
    return float(np.interp(lam, pts, [hl - res(key, l, s)['h'] for l in pts]))


old = dict(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}\{([^}]*)\}', open(OUT + 'numbers_lambound_weights_v2.tex').read()))
MAC = []
for key, sec in SECS:
    lo, hi, const = float(old[f'lbb{sec}lo']), float(old[f'lbb{sec}hi']), float(old[f'lbb{sec}const'])
    MAC += [(f'lbb{sec}lo', old[f'lbb{sec}lo']), (f'lbb{sec}hi', old[f'lbb{sec}hi']), (f'lbb{sec}const', old[f'lbb{sec}const']),
            (f'lbb{sec}med', old[f'lbb{sec}med']), (f'lbb{sec}mean', old[f'lbb{sec}mean']),
            (f'lbb{sec}gapzlo', f'{gap(key, hi, 0.0):.0f}'), (f'lbb{sec}gapzhi', f'{gap(key, lo, 0.0):.0f}'),
            (f'lbb{sec}gaphhi', f'{gap(key, lo, 0.5):.0f}'), (f'lbb{sec}gapzconst', f'{gap(key, const, 0.0):.0f}'),
            (f'lbb{sec}gaphtext', f'{gap(key, hi, 0.5):.0f} to {gap(key, lo, 0.5):.0f}')]
write('numbers_lambound_v9.tex', MAC, 'lambda_numbers.py (weights from policy_lambound.py)')
for n, v in MAC:
    print(n, v)
