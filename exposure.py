"""exposure.py (13 Nov 2026) -- rebuilds the junior-task exposure scores from source.
Source: Eloundou et al. (2024), task-level labels, github.com/openai/GPTs-are-GPTs data/full_labelset.tsv
(O*NET 27.2 tasks; 'automation' = GPT-4 automation rating T0..T4 mapped to 0, .25, .5, .75, 1).
Classification of each task as junior (1), mixed (0.5) or senior (0) is our judgement, written out below.
"""
import csv, itertools, hashlib, os, sys
J, M, S = 1.0, 0.5, 0.0
CLASS = {
 '23-1011.00': {  # Lawyers
  3775: M, 3773: S, 3781: S, 3774: M, 3782: S, 3779: S, 3776: S, 3783: J, 20877: J, 3786: S, 3789: S,
  3780: M, 3777: M, 3778: J, 3785: J, 3788: J, 3787: M, 3790: S, 3794: S, 3792: S, 3791: S, 3793: M},
 '13-2051.00': {  # Financial and Investment Analysts
  21579: S, 21580: M, 21581: M, 21582: M, 21583: S, 21584: J, 21585: S, 21586: J, 21587: S, 21588: S, 21589: J,
  21590: J, 21591: J, 21592: M, 21593: J, 21594: J, 21595: J, 21596: J, 21597: J, 21598: J, 21599: M, 21600: M,
  21601: S, 21602: S, 21603: M, 21604: S}}
# The label file is not redistributed here. Download it from github.com/openai/GPTs-are-GPTs
# (data/full_labelset.tsv) into this folder. The run used the file with the SHA-256 below.
LABELS, LABELS_SHA256 = 'full_labelset.tsv', '094378905e1f3349e50a9a83dc69643a2ef227954d611c8316a46da08cb3d8de'
if not os.path.exists(LABELS):
    sys.exit('full_labelset.tsv not found: download it from https://github.com/openai/GPTs-are-GPTs '
             '(data/full_labelset.tsv) into this folder, then run again.')
if hashlib.sha256(open(LABELS, 'rb').read()).hexdigest() != LABELS_SHA256:
    print('warning: full_labelset.tsv differs from the file used for the paper; results may differ', file=sys.stderr)
rows = list(csv.DictReader(open(LABELS), delimiter='\t'))
res = {}
for code, cl in CLASS.items():
    rs = [r for r in rows if r['O*NET-SOC Code'] == code]
    assert len(rs) == len(cl), (code, len(rs), len(cl))
    a = {int(float(r['Task ID'])): float(r['automation']) for r in rs}
    occ = sum(a.values()) / len(a)
    jw = sum(cl[k] * a[k] for k in a) / sum(cl.values())
    res[code] = (occ, jw, a)
    print(code, 'occupation-level', round(occ, 4), 'junior-weighted', round(jw, 4),
          'tasks J/M/S', sum(v == J for v in cl.values()), sum(v == M for v in cl.values()), sum(v == S for v in cl.values()))
L, B = res['23-1011.00'], res['13-2051.00']
print('ratio occupation-level', round(B[0] / L[0], 3), ' ratio junior-weighted', round(B[1] / L[1], 3))
# sensitivity: move each mixed task to junior or senior, one at a time
for code in CLASS:
    occ, jw, a = res[code]; cl = CLASS[code]; vals = []
    for k in cl:
        for v in (J, M, S):
            c2 = dict(cl); c2[k] = v
            if sum(c2.values()) > 0: vals.append(sum(c2[t] * a[t] for t in a) / sum(c2.values()))
    print(code, 'one-task reclassification range', round(min(vals), 3), round(max(vals), 3))

# ---- Anthropic Economic Index, automation share of conversations by task (period 2026-05-01, published tasks only;
# retrieved 13 Nov 2026 through the Economic Index connector). Occupation level: law 31.49, analysts 44.19.
AEI = {'23-1011.00': {20877: 39, 3773: 34, 3774: 25, 3775: 34, 3777: 39, 3780: 53, 3783: 32},
       '13-2051.00': {21579: 33, 21580: 40, 21585: 39, 21586: 45, 21589: 36, 21590: 43, 21592: 29, 21593: 38, 21594: 52,
                      21595: 26, 21596: 47, 21598: 41, 21599: 39, 21600: 62, 21602: 57}}
OCC = {'23-1011.00': 31.49, '13-2051.00': 44.19}
jwa = {}
for code, a in AEI.items():
    cl = CLASS[code]
    jwa[code] = sum(cl[k] * v for k, v in a.items()) / sum(cl[k] for k in a)
    print(code, 'AEI junior-weighted', round(jwa[code], 2), 'occupation', OCC[code])
rj = jwa['13-2051.00'] / jwa['23-1011.00']; ro = OCC['13-2051.00'] / OCC['23-1011.00']
print('AEI ratio junior-weighted', round(rj, 3), 'occupation', round(ro, 3))
print('baseline ratio = mean of junior-weighted ratios', round((B[1] / L[1] + rj) / 2, 3))

