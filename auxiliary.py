"""aux_v1.py -- rebuild (8 Nov 2026) of the lost shockyear_v2.py, longprofit_v2.py and point40_v2.py
(and their make_*_numbers scripts). Uses the cached solutions of make_paper_assets_v29.py.

shockyear: the adjustment years (shock year, years 5-8, first five years) and the front-loaded attrition check.
longprofit: years until the long-horizon firm's profit exceeds the short-horizon firm's, and the discounted
            gain over years 5-44 ($m, 100 partners), by pass-through.
point40: the 40% stress scenario.
Usage: python3 aux_v1.py shockyear|longprofit|point40
"""
import os
import sys
import numpy as np
from engine_final import SHOCK, P0, BETA
from pathopt import required_p
from core import (th, EXPOSURE, H_LONG, H_SHORT, grid_of, surrogates, sector, hwin, gov, cached, load, make_economy)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
os.makedirs(OUT, exist_ok=True)
SIG = load('sig_v29')
SIGR = load('sigR_v29')
FRONT = 0.35


def sg(v, fmt='{:+.0f}'):
    """Signed number; a value that rounds to zero is written 0."""
    out = fmt.format(v)
    return '0' if out.lstrip('+-').replace(',', '').strip('0.') == '' else out


def write(name, MAC, src):
    with open(OUT + name, 'w') as fh:
        fh.write(f'% generated by auxiliary.py ({src}) -- do not edit by hand\n')
        for n, v in MAC:
            fh.write(f'\\newcommand{{\\{n}}}{{{th(v)}}}\n')


def shockyear():
    MAC = []
    for key, sec in (('Law_09', 'Law'), ('IB', 'IB')):
        p = load(f'gov_E_{key}')['paths']
        r = {}
        for nm, lab in (('my', 'short'), ('pat', 'long')):
            # hiring as a share of the same firm's hiring without the shock, in the same years
            E = np.array(p[f'{nm}_AI']['E']); En = np.array(p[f'{nm}_noAI']['E'])
            r[lab] = dict(yfive=100 * E[SHOCK] / En[SHOCK], adj=100 * E[SHOCK:SHOCK + 4].mean() / En[SHOCK:SHOCK + 4].mean(),
                          zero=int(sum(1 for t in range(SHOCK, SHOCK + 8) if E[t] <= 0.5)),
                          avgfive=100 * E[SHOCK:SHOCK + 5].mean() / En[SHOCK:SHOCK + 5].mean())
            MAC += [(f'sy{sec}{lab}yfive', f'{r[lab]["yfive"]:.0f}'), (f'sy{sec}{lab}adj', f'{r[lab]["adj"]:.0f}'),
                    (f'sy{sec}{lab}zeroyrs', f'{r[lab]["zero"]:d}'), (f'sy{sec}{lab}avgfive', f'{r[lab]["avgfive"]:.0f}')]
        MAC.append((f'sy{sec}gapfive', f'{r["long"]["avgfive"] - r["short"]["avgfive"]:.0f}'))
        pf = load(f'gov_I_{key}')['paths']['my_AI']
        late = 100 * np.mean(pf['E'][30:45]) / pf['e_ss']
        m = sector(key, SIG['Law_09'] if key == 'Law_09' else 1 + EXPOSURE * (SIG['Law_09'] - 1))
        pfr = required_p(m.n_bar, FRONT, m.delta_A, m.delta_P, m.leverage)[0]
        MAC += [(f'sy{sec}frontlate', f'{late:.0f}'), (f'sy{sec}frontp', f'{pfr:.3f}'), (f'sy{sec}frontneed', f'{100 * pfr / (late / 100):.0f}')]
        print(sec, r, late, pfr, flush=True)
    write('numbers_shockyear_v5.tex', MAC, 'shockyear')


def _profits(key, s2, govtag, s):
    m = sector(key, s2)
    PG, AG = grid_of(key)
    spl = surrogates(m, PG, AG, 'v29')
    r = load(f'gov_{govtag}_{key if govtag in ("E", "Fhalf", "Ffull") else key}')
    out = {}
    for nm in ('my', 'pat'):
        e = make_economy(m, spl, H_LONG, True)
        if s > 0:
            e.wP_post = m.w_P + s * (m.mrp_P(P0, m.Ahat_star, 'post', h=2.0) - m.mrp_P(P0, m.Ahat_star, 'pre', h=2.0))
        out[nm] = e.exact_profit(np.array(r['paths'][f'{nm}_AI']['x']), t_max=H_SHORT)
    return out


def longprofit():
    MAC = []
    for anc in ('Proj', 'Real'):
        for key, sec in (('Law_09', 'Law'), ('IB', 'IB')):
            if anc == 'Proj':
                s2 = SIG['Law_09'] if sec == 'Law' else 1 + EXPOSURE * (SIG['Law_09'] - 1)
                k, tags = key, {0.0: 'E', 0.5: 'Fhalf', 1.0: 'Ffull'}
            else:
                s2 = SIGR if sec == 'Law' else 1 + EXPOSURE * (SIGR - 1)
                k, tags = ('Law_R' if sec == 'Law' else 'IB_R'), {0.0: 'R', 0.5: 'Rhalf', 1.0: 'Rfull'}
            for s, w in ((0.0, 'Zero'), (0.5, 'Half'), (1.0, 'Full')):
                pr = cached(f'lp_{k}_{s}', lambda: _profits(k, s2, tags[s], s))
                gap = pr['pat'] - pr['my']
                t_star = next((t for t in range(SHOCK, H_SHORT) if all(gap[u] > 0 for u in range(t, H_SHORT))), None)
                disc = sum(BETA ** (t - SHOCK) * gap[t] for t in range(SHOCK, H_SHORT)) / 1e3
                MAC += [(f'lp{sec}{anc}{w}yrs', 'none' if t_star is None else str(t_star - SHOCK)),
                        (f'lp{sec}{anc}{w}gain', sg(disc))]
                print(anc, sec, s, t_star, round(disc, 2), flush=True)
    write('numbers_longprofit_v5.tex', MAC, 'longprofit')


def point40():
    MAC = [('ftdecl', '40')]
    s2L = load('sigG_40.0')
    MAC += [('ftsigL', f'{s2L:.2f}'), ('ftsigI', f'{1 + EXPOSURE * (s2L - 1):.2f}')]
    from make_cross import crossover_any
    for base, sec, key, s2 in (('Law_09', 'Law', 'Law_G40.0', s2L), ('IB', 'IB', 'IB_G40.0', 1 + EXPOSURE * (s2L - 1))):
        r = load(f'gov_S_{key}')
        m = sector(base, s2)
        PG, AG = grid_of(base)
        spl = surrogates(m, PG, AG, 'v29')
        rise = m.mrp_P(P0, m.Ahat_star, 'post', h=2.0) - m.mrp_P(P0, m.Ahat_star, 'pre', h=2.0)
        rh = cached(f'gov_ft_half_{key}', lambda: gov(m, spl, PG, AG, wP_post=m.w_P + 0.5 * rise))
        rf = cached(f'gov_ft_full_{key}', lambda: gov(m, spl, PG, AG, wP_post=m.w_P + rise))
        MAC += [(f'ft{sec}hmy', f'{100 * r["my"]["hrat"]:.0f}'), (f'ft{sec}hpat', f'{100 * r["pat"]["hrat"]:.0f}'),
                (f'ft{sec}gap', sg(r["gap"], '{:.0f}')), (f'ft{sec}cutmy', f'{100 - 100 * r["my"]["hrat"]:.0f}'),
                (f'ft{sec}cutpat', f'{100 - 100 * r["pat"]["hrat"]:.0f}'), (f'ft{sec}Kmy', f'{100 * r["my"]["K44rat"]:.0f}'),
                (f'ft{sec}Kpat', f'{100 * r["pat"]["K44rat"]:.0f}'), (f'ft{sec}capgap', f'{r["capgap"]:.0f}'),
                (f'ft{sec}gaphalf', f'{rh["gap"]:.0f}'), (f'ft{sec}gapfull', f'{rf["gap"]:.0f}')]
        for s, w in ((0.0, 'zero'), (0.5, 'half'), (1.0, 'full')):
            c, d = crossover_any(key, m, spl, s, rise)
            MAC += [(f'ft{sec}x{w}yrs', 'never' if c is None else str(c - SHOCK)), (f'ft{sec}x{w}gain', f'{d:+,.0f}')]
        MAC.append((f'ft{sec}inside', 'yes' if (r['my']['inside'] and r['pat']['inside']) else 'no'))
        print(sec, MAC[-17:], flush=True)
    law = load('gov_E_Law_09')
    mL = sector('Law_09', SIG['Law_09'])
    mI = sector('IB', 1 + EXPOSURE * (SIG['Law_09'] - 1))
    MAC += [('Lawpneedproj', f'{mL.p_promote / law["my"]["hrat"]:.2f}'), ('Lawfailcut', f'{100 - 100 * mL.p_promote:.0f}'),
            ('IBfailcut', f'{100 - 100 * mI.p_promote:.0f}')]
    write('numbers_point40_v5.tex', MAC, 'point40')


if __name__ == '__main__':
    {'shockyear': shockyear, 'longprofit': longprofit, 'point40': point40}[sys.argv[1]]()
