"""target_numbers.py -- junior stock held by the short-horizon firm in the hiring window (years 9-12), as a
percentage of its pre-shock level, and the first year the senior stock moves; read from the main run
(results_v31.json, make_paper_assets.py). Writes out/numbers_target_v1.tex."""
import json
r = json.load(open('out/results_v31.json'))
L = ['% generated by target_numbers.py -- do not edit by hand']
for key, sec in (('Law_09', 'Law'), ('IB', 'IB')):
    tr = r[key]['transition']; A, P = tr['A'], tr['P']
    tgt = 100 * sum(A[9:13]) / 4 / A[0]
    first = next(t for t in range(len(P)) if abs(P[t] - P[0]) > 1e-6)
    assert all(abs(P[t] - P[0]) < 1e-6 for t in range(9, 13))
    L += [r'\newcommand{\tr%sAtarget}{%d}' % (sec, round(tgt)), r'\newcommand{\tr%sPfirst}{%d}' % (sec, first)]
    print(sec, round(tgt, 1), first)
open('out/numbers_target_v1.tex', 'w').write('\n'.join(L) + '\n')
